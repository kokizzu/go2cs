// Package stdlibmeta builds the converter's embedded record of the exported cross-package
// metadata published by each converted standard-library package's package_info.cs.
//
// It is shared by the genstdlibmeta generator and by the converter's in-process sync test,
// so the committed asset can never drift from src/core without a test failure.
package stdlibmeta

import (
	"bufio"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// AssetFileName is the generated asset the converter embeds, relative to src/go2cs.
const AssetFileName = "stdlib-metadata.txt"

// PackageInfoFileName duplicates the converter's symbols.go constant of the same name. The
// converter is `package main`, so its constants are not importable from here; the value is
// fixed by the emitted file's name and is asserted against the converter's constant by
// TestStdLibMetadataAssetFileName.
const PackageInfoFileName = "package_info.cs"

// SectionPrefix introduces a package section; the remainder of the line is the package's
// dotted name (`math.rand.v2`), matching PackageInfo.PackageName and the `go.<name>` NuGet
// package id. A single '#' introduces a file-level comment line.
const SectionPrefix = "##"

const aliasSectionStart = "// <ExportedTypeAliases>"
const aliasSectionEnd = "// </ExportedTypeAliases>"
const implementPrefix = "[assembly: GoImplement<"

var header = []string{
	"# Code generated by genstdlibmeta from ../core/**/" + PackageInfoFileName + "; DO NOT EDIT.",
	"#",
	"# The converter normally learns a referenced package's exported type aliases and",
	"# interface-implementation records by reading that package's " + PackageInfoFileName + " out of",
	"# the converted-source tree on disk. Under -recurse=nuget there is no such tree -- the",
	"# standard library arrives as pre-compiled go.<pkg> NuGet packages -- so the same facts",
	"# are carried here instead, captured from src/core (the tree push-nuget.ps1",
	"# packs), which makes the embedded record and the published assemblies one commit's output.",
	"#",
	"# Format: '##<dotted package name>' opens a section; its lines are the matching",
	"# " + PackageInfoFileName + " lines verbatim, so the converter's existing parsers read them unchanged.",
	"#",
	"# Regenerate with `go generate .` from src/go2cs; never hand-edit.",
}

// Generate walks convertedRoot for package_info.cs files and returns the asset content, the
// number of package sections written, and any error. Output is deterministic: sections are
// sorted by package name and each carries its matched lines verbatim in file order.
func Generate(convertedRoot string) ([]byte, int, error) {
	sections, err := Collect(convertedRoot)

	if err != nil {
		return nil, 0, err
	}

	if len(sections) == 0 {
		return nil, 0, fmt.Errorf("no %s files found under %q -- is the converted standard library present?", PackageInfoFileName, convertedRoot)
	}

	names := make([]string, 0, len(sections))

	for name := range sections {
		names = append(names, name)
	}

	sort.Strings(names)

	var builder strings.Builder

	for _, line := range header {
		builder.WriteString(line)
		builder.WriteString("\r\n")
	}

	for _, name := range names {
		builder.WriteString("\r\n")
		builder.WriteString(SectionPrefix)
		builder.WriteString(name)
		builder.WriteString("\r\n")

		for _, line := range sections[name] {
			builder.WriteString(line)
			builder.WriteString("\r\n")
		}
	}

	return []byte(builder.String()), len(names), nil
}

// Collect returns, per dotted package name, the package_info.cs lines that carry exported
// cross-package metadata: the <ExportedTypeAliases> section (markers included, so an empty
// section still parses as "no aliases" rather than "unknown") and every GoImplement record.
func Collect(convertedRoot string) (map[string][]string, error) {
	sections := map[string][]string{}

	err := filepath.WalkDir(convertedRoot, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if entry.IsDir() {
			switch entry.Name() {
			case "bin", "obj", "Generated", ".vs", ".git":
				return fs.SkipDir
			}

			return nil
		}

		if entry.Name() != PackageInfoFileName {
			return nil
		}

		relDir, relErr := filepath.Rel(convertedRoot, filepath.Dir(path))

		if relErr != nil {
			return relErr
		}

		lines, readErr := extract(path)

		if readErr != nil {
			return readErr
		}

		sections[strings.ReplaceAll(filepath.ToSlash(relDir), "/", ".")] = lines

		return nil
	})

	if err != nil {
		return nil, err
	}

	return sections, nil
}

// extract pulls the metadata-bearing lines out of one package_info.cs, preserving their
// original spelling so the converter's regex parsers can consume them unchanged.
func extract(packageInfoFile string) ([]string, error) {
	file, err := os.Open(packageInfoFile)

	if err != nil {
		return nil, err
	}

	defer file.Close()

	var lines []string
	inAliasSection := false

	scanner := bufio.NewScanner(file)

	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)

		switch {
		case trimmed == aliasSectionStart:
			inAliasSection = true
			lines = append(lines, trimmed)
		case trimmed == aliasSectionEnd:
			inAliasSection = false
			lines = append(lines, trimmed)
		case inAliasSection && strings.HasPrefix(trimmed, "[assembly: GoTypeAlias("):
			lines = append(lines, trimmed)
		case strings.HasPrefix(trimmed, implementPrefix):
			lines = append(lines, trimmed)
		}
	}

	return lines, scanner.Err()
}
