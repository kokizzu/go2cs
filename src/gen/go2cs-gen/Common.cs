    public static readonly Assembly? EntryAssembly;
    public static readonly string AssemblyName;
    public static readonly string Version;
    public static readonly string GeneratedCodeAttribute;
    public static readonly Regex PointerExpr;
    private static readonly HashSet<char> InvalidChars;

    public const string AutoGeneratedHeader = 
        """
        //---------------------------------------------------------
        // <auto-generated>
        //     This code was generated by a tool. Changes to this
        //     file may cause incorrect behavior and will be lost
        //     if the code is regenerated.
        // </auto-generated>
        //---------------------------------------------------------
        """;

    static Common()
    {
        const string FallBackAssemblyName = nameof(go2cs);
        const string FallBackVersion = "0.0.1";

        try
        {
            EntryAssembly = Assembly.GetAssembly(typeof(Common));
            AssemblyName = EntryAssembly?.GetName().Name ?? FallBackAssemblyName;
            Version = getVersion();
        }
        catch
        {
            EntryAssembly = null;
            AssemblyName = FallBackAssemblyName;
            Version = FallBackVersion;
        }

        // global::-rooted so a Go type in the SAME package class can never shadow the attribute
        // name (the generated partials sit inside `<pkg>_package`, where every Go type name is a
        // sibling member — the same collision class as the System.Range/System.Type audit).
        GeneratedCodeAttribute = $"""global::System.CodeDom.Compiler.GeneratedCode("{AssemblyName}", "{Version}")""";

        PointerExpr = new Regex($"^(?:[^<]*)?{PointerPrefix}<.*$", RegexOptions.Compiled);
        InvalidChars = [..Path.GetInvalidFileNameChars()];

        return;

        string getVersion()
        {
            Version? version = EntryAssembly?.GetName().Version;
            return version is null ? FallBackVersion : $"{version.Major}.{version.Minor}.{version.Build}";
        }
    }

    public static bool IsGenericType(string typeName)
    {
        return typeName.Contains('<') && typeName.Contains('>');
    }

    public static string GetSimpleName(string typeName, bool dropGeneric = false, bool dropCollisionPrefix = false)
    {
        // Check if type name is a pointer, i.e., ж<T>. Match the prefix as `ж<` specifically — a bare
        // `ж` scan mis-fires on the marker glyph EMBEDDED in an identifier (crypto/elliptic's
        // `P256PointжnistPoint` proxy), mangling a VALUE embed's simple name (`nistCurve<…ж…>` →
        // `istPoint.Value`) so its promoted member access binds a nonexistent hop (CS0103/CS1061).
        int startIndex = typeName.IndexOf($"{PointerPrefix}<", StringComparison.Ordinal);
        bool isPointer = false;

        // For pointer types, get dereferenced underlying type
        if (startIndex > -1 && typeName.EndsWith(">"))
        {
            typeName = $"{typeName[(startIndex + 2)..^1]}";
            isPointer = true;
        }

        string[] parts = typeName.Split('.');

        string simpleName = $"{parts[^1]}{(isPointer ? ".Value" : "")}";

        if (dropGeneric)
        {
            startIndex = typeName.IndexOf('<');

            if (startIndex > 1 && typeName.EndsWith(">"))
                simpleName = $"{simpleName[..startIndex]}";
        }

        if (dropCollisionPrefix && simpleName.StartsWith(ShadowVarMarker, StringComparison.Ordinal))
            simpleName = simpleName[ShadowVarMarker.Length..];

        return simpleName;
    }

    // A generated reference that BEGINS with the root namespace must be global::-qualified:
    // inside a package whose namespace nests a same-named segment (go/build/constraint →
    // namespace go.go.build), C# binds the leading `go` RELATIVELY to go.go, so every
    // `go.…` type reference in the generated adapter failed (CS0234 ×50 + CS0538 ×13).
    // Qualifies each type-reference position (string start, after '<', '(', ',' or space);
    // an interior `.go.` segment (go.go.build itself) is never touched.
    private static readonly Regex s_rootTypeRefRegex = new(@"(^|[<(,\s])go\.", RegexOptions.Compiled);

    public static string GlobalQualify(string typeName)
    {
        return s_rootTypeRefRegex.Replace(typeName, "$1global::go.");
    }

    // RefKindPrefix renders a parameter's ref-kind modifier ("in " / "ref " / "out ") so a
    // generated signature matches an interface member declared with one (the hand-finished
    // io stub's Reader.Read(in slice<byte>) - an explicit impl without it is CS0539).
    public static string RefKindPrefix(RefKind refKind) => refKind switch
    {
        RefKind.In => "in ",
        RefKind.Ref => "ref ",
        RefKind.Out => "out ",
        _ => "",
    };

    public static string GetFullTypeName(this ITypeSymbol? typeSymbol, bool useDisplayString = false)
    {
        switch (typeSymbol)
        {
            case null:
                return string.Empty;
            case IArrayTypeSymbol arrayType:
                return $"{GetFullTypeName(arrayType.ElementType)}[]";
            case INamedTypeSymbol { IsGenericType: true } namedType:
                ImmutableArray<ITypeSymbol> typeArgs = namedType.TypeArguments;
                IEnumerable<string> typeArgNames = typeArgs.Select(typeArg => typeArg.GetFullTypeName(useDisplayString));
                return $"{namedType.Name}<{string.Join(", ", typeArgNames)}>";
            default:
                return useDisplayString ? typeSymbol.ToDisplayString() : typeSymbol.Name;
        }
    }

    public static string[] GetFullyQualifiedUsingStatements(SyntaxTree syntaxTree, SemanticModel semanticModel)
    {
        return syntaxTree
            .GetRoot()
            .DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            // Skip `global using` directives: they are already in scope in every file of the
            // compilation (including generated ones), so re-emitting them as file-local `using`
            // here would collide with the original global alias (CS1537 "appeared previously").
            .Where(directive => directive.GlobalKeyword.IsKind(SyntaxKind.None))
            .Select(directive =>
            {
                if (directive.Name is null)
                    return "";

                // For alias directives, maintain the alias but fully qualify the target
                if (directive.Alias is not null)
                {
                    ISymbol? symbol = semanticModel.GetSymbolInfo(directive.Name).Symbol;

                    if (symbol is not null)
                    {
                        string fullyQualifiedName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                        return $"using {directive.Alias.Name.Identifier.Text} = {fullyQualifiedName};";
                    }
                    
                    return directive.GetText().ToString().Trim();
                }
                
                // Static using directives
                if (directive.StaticKeyword.Kind() is not SyntaxKind.None)
                {
                    ISymbol? symbol = semanticModel.GetSymbolInfo(directive.Name).Symbol;

                    if (symbol is not null)
                    {
                        string fullyQualifiedName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                        return $"using static {fullyQualifiedName};";
                    }

                    return directive.GetText().ToString().Trim();
                }

                // Standard namespace imports
                ISymbol? namespaceSymbol = semanticModel.GetSymbolInfo(directive.Name).Symbol;

                if (namespaceSymbol is not null)
                {
                    return $"using {namespaceSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)};";
                }
                
                return directive.GetText().ToString().Trim();
            })
            .ToArray();
    }

    public static string GetValidFileName(string fileName)
    {
        return new string(fileName.Replace("@", "").Select(c => InvalidChars.Contains(c) ? '_' : c).ToArray());
    }

    /// <summary>
    /// Returns every base interface of <paramref name="type"/>, recovering the ones the semantic
    /// model reports as INACCESSIBLE because this generator has not emitted their access modifier yet.
    /// </summary>
    /// <remarks>
    /// The converter emits a Go type as a bare <c>[GoType] partial interface X</c> nested in the
    /// package class and leaves the access modifier to this generator, which derives it from the Go
    /// export convention (<see cref="GetScope"/> — public for an exported name, internal otherwise).
    /// A generator cannot see its own output, so until that partial exists the declaration is a
    /// PRIVATE nested type: accessible from inside its own package class, and inaccessible from any
    /// other class in the assembly. A type in another package class that names it as a base therefore
    /// binds to an <see cref="IErrorTypeSymbol"/> with zero members, and every method the base
    /// contributes silently vanishes from the adapter/shell — while the FINAL compilation, which does
    /// have the generated partial, still demands them (CS0535). io's external test package hit this:
    /// <c>io_test.closer : io.Closer</c> and <c>io_test.testMultiWriter_sink : io.Writer</c> lost
    /// <c>Close()</c>/<c>Write()</c>, while the same <c>io.Closer</c> resolved normally as a base of
    /// <c>io.ReadCloser</c> inside its own class.
    ///
    /// The accessibility seen here is PROVISIONAL, so recovering the candidate is sound rather than a
    /// bypass: this generator is about to declare that same type <c>public</c> or <c>internal</c>, and
    /// both are reachable from anywhere in the assembly. Recovery is therefore limited to a candidate
    /// interface declared in THIS compilation's assembly — a genuinely inaccessible foreign type keeps
    /// its error symbol. A recovered base's own transitive bases are folded in too, since
    /// <see cref="ITypeSymbol.AllInterfaces"/> cannot traverse through an error symbol.
    /// </remarks>
    /// <summary>
    /// Determines if <paramref name="typeDeclaration"/> is the DEFINING part of its type, i.e. the
    /// one carrying the converter's <c>[GoType]</c> attribute.
    /// </summary>
    /// <remarks>
    /// A converted Go type has two converter-written parts: the <c>[GoType]</c> declaration in the
    /// package source, which carries the members and the definition token, and the condensed
    /// accessibility-pinning declaration in package_info.cs's <c>TypeAccessibility</c> section,
    /// which carries only the access modifier. Any lookup that resolves a type by NAME through the
    /// syntax trees can land on either one, so a lookup that goes on to read members or the
    /// definition token must prefer this one — the accessibility part is empty by construction.
    /// </remarks>
    public static bool IsGoTypeDefinition(this BaseTypeDeclarationSyntax typeDeclaration)
    {
        foreach (AttributeListSyntax attributeList in typeDeclaration.AttributeLists)
        {
            foreach (AttributeSyntax attribute in attributeList.Attributes)
            {
                string name = attribute.Name.ToString();

                if (name == GoTypeAttributeName || name == $"{GoTypeAttributeName}Attribute")
                    return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Simple name of the converter-emitted type-definition attribute.
    /// </summary>
    public const string GoTypeAttributeName = "GoType";

    public static IEnumerable<INamedTypeSymbol> GetAllBaseInterfaces(this INamedTypeSymbol type, Compilation compilation)
    {
        HashSet<INamedTypeSymbol> seen = new(SymbolEqualityComparer.Default);
        List<INamedTypeSymbol> resolved = [];

        void Add(INamedTypeSymbol candidate)
        {
            INamedTypeSymbol recovered = RecoverProvisionallyInaccessible(candidate, compilation);

            if (!seen.Add(recovered))
                return;

            resolved.Add(recovered);

            // Only a RECOVERED base needs its own bases folded in: an accessible one already
            // contributed them through the AllInterfaces walk that reached it.
            if (!ReferenceEquals(recovered, candidate))
            {
                foreach (INamedTypeSymbol nested in recovered.AllInterfaces)
                    Add(nested);
            }
        }

        foreach (INamedTypeSymbol baseInterface in type.AllInterfaces)
            Add(baseInterface);

        return resolved;
    }

    private static INamedTypeSymbol RecoverProvisionallyInaccessible(INamedTypeSymbol candidate, Compilation compilation)
    {
        if (candidate is not IErrorTypeSymbol { CandidateReason: CandidateReason.Inaccessible } error)
            return candidate;

        foreach (ISymbol symbol in error.CandidateSymbols)
        {
            if (symbol is INamedTypeSymbol { TypeKind: TypeKind.Interface } named &&
                SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, compilation.Assembly))
                return named;
        }

        return candidate;
    }

    // Roslyn requires every AddSource hintName within a generator to be unique, and it compares them
    // CASE-INSENSITIVELY. Two Go types that differ only in case (e.g. exported `Pinner` and unexported
    // `pinner`, both real, distinct C# types) therefore collide on `…pinner.g.cs` and the generator
    // throws — suppressing ALL of its output. Disambiguate the later collisions with a numeric suffix;
    // the hintName is only an internal file label, so any unique value is correct.
    public static string GetUniqueHintName(HashSet<string> emitted, string hintName)
    {
        if (emitted.Add(hintName))
            return hintName;

        string baseName = hintName.EndsWith(".g.cs") ? hintName[..^5] : hintName;
        string suffix = hintName.EndsWith(".g.cs") ? ".g.cs" : "";

        int index = 1;
        string candidate;

        do
        {
            candidate = $"{baseName}.{index++}{suffix}";
        }
        while (!emitted.Add(candidate));

        return candidate;
    }

    public static string GetUnsanitizedIdentifier(string identifier)
    {
        return identifier.StartsWith("@") ? identifier[1..] : identifier;
    }

    // A Go method/field name that is a C# reserved keyword (encoding/gob's `string()` method)
    // must be `@`-escaped to be a valid C# identifier. Symbol names read from Roslyn
    // (IMethodSymbol.Name) arrive UNescaped, unlike syntax Identifier.Text; escape them before
    // they reach emitted C# (an explicit interface impl `ΔgobType.string()` was a parse error).
    public static string EscapeCsKeyword(string identifier)
    {
        if (identifier.StartsWith("@"))
            return identifier;

        return SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None ? $"@{identifier}" : identifier;
    }

    // A type name written in a DECLARATION position needs the escape for CONTEXTUAL keywords too:
    // `public record ΔClone()` parses as a positional RECORD DECLARATION rather than a method
    // returning the struct named `record` (net/http/fcgi's `type record struct` — CS1514/CS1519 x7 in
    // the generated value-clone). EscapeCsKeyword above covers only reserved words, which is what a
    // member-name position needs. A generic name keeps its type ARGUMENTS unescaped (`@record<T>`).
    public static string EscapeCsTypeName(string typeName)
    {
        if (string.IsNullOrWhiteSpace(typeName) || typeName.StartsWith("@"))
            return typeName;

        int angle = typeName.IndexOf('<');
        string simpleName = angle < 0 ? typeName : typeName.Substring(0, angle);

        if (SyntaxFacts.GetKeywordKind(simpleName) == SyntaxKind.None && SyntaxFacts.GetContextualKeywordKind(simpleName) == SyntaxKind.None)
            return typeName;

        return $"@{typeName}";
    }

    public static string GetScope(string identifier)
    {
        char firstChar = identifier[0];

        // A '_'-prefixed Go identifier (other than the bare blank '_') is unexported → internal,
        // matching the converter's getAccess. Treating any '_' lead as public made a generated
        // promoted accessor for an embedded `*_func` public while the converter's `internal partial
        // ref` declaration was internal (CS8799).
        if (firstChar == '_')
            return identifier.Length == 1 ? "public" : "internal";

        return char.IsUpper(firstChar) ? "public" : "internal";
    }

    // Returns the explicit C# access modifier on a type declaration (e.g. the converter-emitted
    // `public partial struct d`), or null when none is present. This lets an explicit modifier
    // from the converter override the name-based GetScope — e.g. an unexported type that the
    // converter publicized because it is used as the type of an exported field (CS0051/CS0052).
    public static string GetExplicitAccessModifier(BaseTypeDeclarationSyntax typeDeclaration)
    {
        foreach (SyntaxToken modifier in typeDeclaration.Modifiers)
        {
            switch (modifier.Kind())
            {
                case SyntaxKind.PublicKeyword:
                    return "public";
                case SyntaxKind.InternalKeyword:
                    return "internal";
                case SyntaxKind.PrivateKeyword:
                    return "private";
                case SyntaxKind.ProtectedKeyword:
                    return "protected";
            }
        }

        return null;
    }
}
