using System.Collections.Generic;
using System.Linq;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using go;

namespace GolibTests;

/// <summary>
/// Round 4's MARKED wrapper shapes, as the converter now emits them: the wrapper frame is kept (and
/// panicwrap modelled) only for the panic the wrapper's own receiver helper raised.
/// </summary>
[TestClass]
public class PanicFramesRound4MarkedTests
{
    private const string Pkg = "panicframesprobe.";

    // Go: gopanic | panicmem | sigpanic | (*OuterV).IM | owner.
    [TestMethod]
    public void AMarkedPromotedWrapperOnANilPointerKeepsGosList()
    {
        List<string> names = panicframesprobe_package.onGoroutine(panicframesprobe_package.nilThroughMarkedPromotedWrapper);
        int end = names.IndexOf(Pkg + "nilThroughMarkedPromotedWrapper", 3);
        Assert.IsTrue(end >= 3, string.Join(" | ", names));

        CollectionAssert.AreEqual(
            new[] { "runtime.gopanic", "runtime.panicmem", "runtime.sigpanic", Pkg + "(*OuterV).IM", Pkg + "nilThroughMarkedPromotedWrapper" },
            names.GetRange(3, end - 3 + 1), string.Join(" | ", names));
    }

    // The wrapper frame reads <autogenerated>:1, as Go's autogenerated wrapper does.
    [TestMethod]
    public void AKeptWrapperFrameIsPositionedAtAutogeneratedLineOne()
    {
        List<(string function, string file, long line)> frames =
            panicframesprobe_package.onGoroutine(panicframesprobe_package.nilThroughInterfaceWrapperWithFiles);

        (string function, string file, long line) wrapper = frames.FirstOrDefault(frame => frame.function == "wrapperprobe.I.M");

        Assert.AreEqual("wrapperprobe.I.M", wrapper.function, string.Join(" | ", frames.Select(frame => frame.function)));
        Assert.AreEqual("<autogenerated>", wrapper.file);
        Assert.AreEqual(1L, wrapper.line);
    }

    // panicwrap's recovered VALUE is Go's message, not a nil-dereference.
    [TestMethod]
    public void PanicwrapRecoversGosMessage()
    {
        panicframesprobe_package.onGoroutine(panicframesprobe_package.nilThroughPointerWrapper);

        Assert.AreEqual(panicframesprobe_package.PanicwrapMessage, panicframesprobe_package.recoveredPanicwrap?.ToString());
    }

    // The receiver as the CONVERTER passes it (golib's nil, the canonical NON-null NilBox), not C#'s null.
    // Go: gopanic | panicwrap | (*T).M | owner, recovering Go's message.
    [TestMethod]
    public void ANilBoxThroughTheValueMethodWrapperIsPanicwrap()
    {
        List<string> names = panicframesprobe_package.onGoroutine(panicframesprobe_package.nilBoxThroughPointerWrapper);
        int end = names.IndexOf(Pkg + "nilBoxThroughPointerWrapper", 3);
        Assert.IsTrue(end >= 3, string.Join(" | ", names));

        CollectionAssert.AreEqual(
            new[] { "runtime.gopanic", "runtime.panicwrap", Pkg + "(*T).M", Pkg + "nilBoxThroughPointerWrapper" },
            names.GetRange(3, end - 3 + 1), string.Join(" | ", names));
        Assert.AreEqual(panicframesprobe_package.PanicwrapMessage, panicframesprobe_package.recoveredPanicwrap?.ToString());
    }

    // Go: gopanic | panicmem | sigpanic | (*OuterV).IM | owner.
    [TestMethod]
    public void ANilBoxThroughTheMarkedPromotedWrapperKeepsGosList()
    {
        List<string> names = panicframesprobe_package.onGoroutine(panicframesprobe_package.nilBoxThroughMarkedPromotedWrapper);
        int end = names.IndexOf(Pkg + "nilBoxThroughMarkedPromotedWrapper", 3);
        Assert.IsTrue(end >= 3, string.Join(" | ", names));

        CollectionAssert.AreEqual(
            new[] { "runtime.gopanic", "runtime.panicmem", "runtime.sigpanic", Pkg + "(*OuterV).IM", Pkg + "nilBoxThroughMarkedPromotedWrapper" },
            names.GetRange(3, end - 3 + 1), string.Join(" | ", names));
    }
}
