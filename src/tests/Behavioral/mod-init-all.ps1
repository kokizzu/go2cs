<#
.SYNOPSIS
    Maintenance one-off: re-initialize the Go module in every behavioral test project.

.DESCRIPTION
    Deletes each project's go.mod and .csproj and runs `go mod init go2cs/<Name>` to recreate the
    module. The .csproj is regenerated by the next transpile, so removing it here is how a stale
    hand-edited project file gets levelled.

    Two properties this script did not used to have, both of which are safety rather than polish:

    * It is anchored to $PSScriptRoot, not to the caller's current directory. It deletes `*.csproj`,
      and a `Get-ChildItem -Directory` over wherever you happened to be standing is not something
      that should be able to do that.

    * A directory only qualifies if it CONTAINS GO SOURCE -- the same rule check-no-regression.ps1
      uses to decide what a behavioral target is (cf. commit 2cbe71947). The old name-based skip
      listed BehavioralTests only, so once BehavioralRunner arrived (2026-06-30) this script would
      have deleted BehavioralRunner.csproj and left a hand-written C# tool with a Go module in it.
      Go-source presence covers both, and any tooling directory added later.

.NOTES
    Portable: PowerShell 5.1 (Windows) or PowerShell 7+ (any platform). No path literals, and
    Remove-Item rather than the `del` alias.
#>
[CmdletBinding()]
param()

. (Join-Path $PSScriptRoot '_paths.ps1')

# Top-level only, deliberately: a nested sub-library (IoLike/FsLike, VersionedImport/vlib, ...) is a
# package WITHIN its parent's module and must not get a go.mod of its own.
$directories = Get-ChildItem -Path $BehavioralRoot -Directory

foreach ($dir in $directories) {
    if (-not (Get-ChildItem $dir.FullName -Filter *.go -File -ErrorAction SilentlyContinue)) {
        Write-Host "Skipping $($dir.Name) (no Go source -- harness tooling, not a test target)" -ForegroundColor Yellow
        continue
    }

    Write-Host "Processing directory: $($dir.FullName)"

    Push-Location $dir.FullName

    try {
        # Absent files are not an error here: a freshly added project has neither yet.
        Remove-Item 'go.mod' -Force -ErrorAction SilentlyContinue
        Remove-Item '*.csproj' -Force -ErrorAction SilentlyContinue

        $moduleName = "go2cs/$($dir.Name)"
        Write-Host "Running: go mod init $moduleName"
        go mod init $moduleName

        if ($LASTEXITCODE -eq 0) {
            Write-Host "Successfully initialized Go module in $($dir.Name)" -ForegroundColor Green
        } else {
            Write-Host "Failed to initialize Go module in $($dir.Name)" -ForegroundColor Red
        }
    }
    catch {
        Write-Host "Error occurred: $_" -ForegroundColor Red
    }
    finally {
        Pop-Location
    }
}

Write-Host "All directories processed." -ForegroundColor Cyan
